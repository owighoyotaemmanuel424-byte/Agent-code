import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { gunzipSync } from "node:zlib";
import { describe, expect, it } from "vitest";
import { AuthService, InMemoryAuthStore } from "@freebuff/auth";
import { openSqliteDatabase } from "@freebuff/db";
import { createWebApp } from "../../../apps/web/src/app";
import { buildApp } from "../../../apps/web/src/builder";
import { LocalHostingAdapter } from "../../../apps/web/src/hosting";
import { AppRuntime } from "../../../apps/web/src/runtime";
import { PlatformStore } from "../../../apps/web/src/store";
import { ScriptedModel } from "../../support/scripted-model";

const SPEC = {
  name: "Recipe Box",
  tagline: "Save the recipes you actually cook",
  theme: { primary: "#2f81f7", accent: "#3fb950", radius: 10, dark: true },
  entities: [
    {
      name: "recipes",
      label: "Recipes",
      fields: [
        { name: "title", label: "Title", type: "text", required: true },
        { name: "servings", label: "Servings", type: "integer", required: false },
        { name: "notes", label: "Notes", type: "longtext", required: false },
        { name: "favourite", label: "Favourite", type: "boolean", required: false },
        { name: "cooked_on", label: "Cooked on", type: "date", required: false },
      ],
    },
  ],
};

const ORIGIN = "http://web.test";

const jsonRequest = (url: string, body: unknown, token?: string): Request =>
  new Request(url, {
    method: "POST",
    headers: {
      "content-type": "application/json",
      ...(token === undefined ? {} : { authorization: `Bearer ${token}` }),
    },
    body: JSON.stringify(body),
  });

describe("Phase 4 gate: one prompt to a deployed app", () => {
  it("deploys an app with auth, database, storage and an eject bundle", async () => {
    const root = await mkdtemp(join(tmpdir(), "freebuff-web-gate-"));
    const model = new ScriptedModel([{ text: JSON.stringify(SPEC) }]);
    const db = openSqliteDatabase(join(root, "platform.sqlite"));
    try {
      const store = new PlatformStore({ db });
      const auth = new AuthService({
        store: new InMemoryAuthStore(),
        secret: "test-secret-that-is-long-enough-1234",
      });
      const hosting = new LocalHostingAdapter({ root });
      const runtime = new AppRuntime({ root, store });
      const app = createWebApp({
        store,
        auth,
        runtime,
        root,
        modelReady: true,
        modelId: "scripted-model",
        builder: {
          build: (options) =>
            buildApp(
              { store, hosting, root, model, modelId: "scripted-model" },
              options,
            ),
        },
      });

      const landing = await app.fetch(new Request(`${ORIGIN}/`));
      expect(landing.status).toBe(200);
      expect(await landing.text()).toContain("Describe an app");

      const emptyPrompt = await app.fetch(
        jsonRequest(`${ORIGIN}/api/apps`, { prompt: "" }),
      );
      expect(emptyPrompt.status).toBe(422);

      const built = await app.fetch(
        jsonRequest(`${ORIGIN}/api/apps`, {
          prompt: "A recipe box with photos and favourites",
        }),
      );
      expect(built.status).toBe(201);
      const payload = (await built.json()) as {
        app: { id: string; slug: string; status: string; spec: typeof SPEC };
        url: string;
        timeline: { step: string; status: string }[];
        usage: { inputTokens: number; outputTokens: number };
      };
      const appId = payload.app.id;
      expect(payload.app.status).toBe("deployed");
      expect(payload.app.spec.name).toBe("Recipe Box");
      expect(payload.url).toMatch(/^http:\/\/web\.test\/s\/recipe-box-[a-f0-9]{8}\/$/);
      expect(payload.timeline.map((step) => step.step)).toEqual([
        "design",
        "scaffold",
        "deploy",
      ]);
      expect(payload.usage.inputTokens).toBeGreaterThan(0);

      // Deployed URL serves the generated app and its assets.
      const page = await app.fetch(new Request(payload.url));
      expect(page.status).toBe(200);
      const pageHtml = await page.text();
      expect(pageHtml).toContain("Recipe Box");
      expect(pageHtml).toContain(`name="freebuff-app-id" content="${appId}"`);
      const script = await app.fetch(new Request(new URL("app.js", payload.url).toString()));
      expect(script.status).toBe(200);
      expect(await script.text()).toContain("Generated by freebuff app builder");
      const styles = await app.fetch(new Request(new URL("styles.css", payload.url).toString()));
      expect(styles.status).toBe(200);
      expect(await styles.text()).toContain("#2f81f7");

      const missing = await app.fetch(new Request(`${ORIGIN}/s/not-a-real-app/`));
      expect(missing.status).toBe(404);

      // Real magic-link auth, two distinct accounts.
      const signIn = async (email: string): Promise<string> => {
        const requested = await app.fetch(
          jsonRequest(`${ORIGIN}/api/apps/${appId}/auth/request`, { email }),
        );
        expect(requested.status).toBe(200);
        const { link } = (await requested.json()) as { link: string };
        const token = new URL(link).searchParams.get("token");
        expect(token).toBeTruthy();
        const complete = await app.fetch(
          jsonRequest(`${ORIGIN}/api/apps/${appId}/auth/complete`, { token }),
        );
        expect(complete.status).toBe(200);
        return ((await complete.json()) as { sessionToken: string }).sessionToken;
      };

      const owner = await signIn("owner@example.com");
      const intruder = await signIn("intruder@example.com");

      const me = await app.fetch(
        new Request(`${ORIGIN}/api/apps/${appId}/auth/me`, {
          headers: { authorization: `Bearer ${owner}` },
        }),
      );
      expect(me.status).toBe(200);
      expect(((await me.json()) as { user: { email: string } }).user.email).toBe(
        "owner@example.com",
      );

      // Database rows are owned, validated and typed.
      const created = await app.fetch(
        jsonRequest(
          `${ORIGIN}/api/apps/${appId}/data/recipes`,
          {
            title: "Pancakes",
            servings: 4,
            notes: "Rest the batter",
            favourite: true,
            cooked_on: "2026-11-19",
          },
          owner,
        ),
      );
      expect(created.status).toBe(201);
      const createdRow = ((await created.json()) as {
        row: { id: string; title: string; favourite: boolean; cooked_on: string };
      }).row;
      expect(createdRow.title).toBe("Pancakes");
      expect(createdRow.favourite).toBe(true);
      expect(createdRow.cooked_on).toBe("2026-11-19");

      const ownerList = await app.fetch(
        new Request(`${ORIGIN}/api/apps/${appId}/data/recipes`, {
          headers: { authorization: `Bearer ${owner}` },
        }),
      );
      expect(((await ownerList.json()) as { rows: unknown[] }).rows).toHaveLength(1);

      const intruderList = await app.fetch(
        new Request(`${ORIGIN}/api/apps/${appId}/data/recipes`, {
          headers: { authorization: `Bearer ${intruder}` },
        }),
      );
      expect(((await intruderList.json()) as { rows: unknown[] }).rows).toHaveLength(0);

      const unauthenticated = await app.fetch(
        new Request(`${ORIGIN}/api/apps/${appId}/data/recipes`),
      );
      expect(unauthenticated.status).toBe(401);

      const wrongType = await app.fetch(
        jsonRequest(
          `${ORIGIN}/api/apps/${appId}/data/recipes`,
          { title: "Bad", servings: "many" },
          owner,
        ),
      );
      expect(wrongType.status).toBe(422);

      const unknownField = await app.fetch(
        jsonRequest(
          `${ORIGIN}/api/apps/${appId}/data/recipes`,
          { title: "Bad", ownerId: "someone-else" },
          owner,
        ),
      );
      expect(unknownField.status).toBe(422);

      const unknownCollection = await app.fetch(
        new Request(`${ORIGIN}/api/apps/${appId}/data/secrets`, {
          headers: { authorization: `Bearer ${owner}` },
        }),
      );
      expect(unknownCollection.status).toBe(404);

      const stolenDelete = await app.fetch(
        new Request(`${ORIGIN}/api/apps/${appId}/data/recipes/${createdRow.id}`, {
          method: "DELETE",
          headers: { authorization: `Bearer ${intruder}` },
        }),
      );
      expect(stolenDelete.status).toBe(403);

      const ownDelete = await app.fetch(
        new Request(`${ORIGIN}/api/apps/${appId}/data/recipes/${createdRow.id}`, {
          method: "DELETE",
          headers: { authorization: `Bearer ${owner}` },
        }),
      );
      expect(ownDelete.status).toBe(200);

      // File storage with ownership and limits.
      const bytes = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 1, 2, 3, 4]);
      const uploaded = await app.fetch(
        jsonRequest(
          `${ORIGIN}/api/apps/${appId}/files`,
          {
            name: "pancakes.png",
            contentType: "image/png",
            contentBase64: bytes.toString("base64"),
          },
          owner,
        ),
      );
      expect(uploaded.status).toBe(201);
      const fileId = ((await uploaded.json()) as { file: { id: string } }).file.id;

      const download = await app.fetch(
        new Request(`${ORIGIN}/api/apps/${appId}/files/${fileId}`, {
          headers: { authorization: `Bearer ${owner}` },
        }),
      );
      expect(download.status).toBe(200);
      expect(download.headers.get("content-type")).toBe("image/png");
      expect(Buffer.from(await download.arrayBuffer()).equals(bytes)).toBe(true);

      const stolenDownload = await app.fetch(
        new Request(`${ORIGIN}/api/apps/${appId}/files/${fileId}`, {
          headers: { authorization: `Bearer ${intruder}` },
        }),
      );
      expect(stolenDownload.status).toBe(403);

      const disallowedType = await app.fetch(
        jsonRequest(
          `${ORIGIN}/api/apps/${appId}/files`,
          { name: "x.html", contentType: "text/html", contentBase64: "aGVsbG8=" },
          owner,
        ),
      );
      expect(disallowedType.status).toBe(422);

      const oversized = await app.fetch(
        jsonRequest(
          `${ORIGIN}/api/apps/${appId}/files`,
          {
            name: "big.bin",
            contentType: "application/octet-stream",
            contentBase64: Buffer.alloc(2 * 1024 * 1024 + 1).toString("base64"),
          },
          owner,
        ),
      );
      expect(oversized.status).toBe(422);

      const listedFiles = ((await (
        await app.fetch(
          new Request(`${ORIGIN}/api/apps/${appId}/files`, {
            headers: { authorization: `Bearer ${owner}` },
          }),
        )
      ).json()) as { files: unknown[] }).files;
      expect(listedFiles).toHaveLength(1);

      // Eject: a real gzipped tarball of the source tree.
      const eject = await app.fetch(
        new Request(`${ORIGIN}/api/apps/${appId}/eject`),
      );
      expect(eject.status).toBe(200);
      expect(eject.headers.get("content-type")).toBe("application/gzip");
      const tar = gunzipSync(Buffer.from(await eject.arrayBuffer()));
      for (const name of [
        "index.html",
        "app.js",
        "styles.css",
        "schema.sql",
        "freebuff.app.json",
        "README.md",
      ]) {
        expect(tar.includes(Buffer.from(name))).toBe(true);
      }
      expect(tar.includes(Buffer.from('CREATE TABLE IF NOT EXISTS "recipes"'))).toBe(true);

      // GitHub eject requires a token; the real push is covered by its own test.
      const denied = await app.fetch(
        jsonRequest(`${ORIGIN}/api/apps/${appId}/eject/github`, {}, owner),
      );
      expect(denied.status).toBe(401);

      const detail = await app.fetch(new Request(`${ORIGIN}/api/apps/${appId}`));
      expect(((await detail.json()) as { app: { status: string } }).app.status).toBe(
        "deployed",
      );
    } finally {
      db.close();
      await rm(root, { recursive: true, force: true });
    }
  }, 120_000);
});
