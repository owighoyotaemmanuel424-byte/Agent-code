import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import type { ChatModel } from "@freebuff/llm-providers";
import { AppError, newId } from "@freebuff/shared";
import type { AgentUsage } from "@freebuff/shared";
import { generateAppSpec } from "./generate";
import { scaffoldApp } from "./scaffold";
import type { GeneratedFile } from "./scaffold";
import type { HostingAdapter } from "./hosting";
import type { AppRecord, PlatformStore } from "./store";
import type { AppSpec } from "./spec";

export interface BuildStep {
  readonly step: string;
  readonly status: "ok";
  readonly detail?: string;
}

export interface BuilderDeps {
  readonly store: PlatformStore;
  readonly hosting: HostingAdapter;
  readonly root: string;
  readonly model: ChatModel;
  readonly modelId: string;
  readonly maxOutputTokens?: number;
  readonly now?: () => Date;
}

export interface BuildOptions {
  readonly prompt: string;
  readonly signal?: AbortSignal;
  readonly ownerId?: string;
}

export interface BuildResult {
  readonly app: AppRecord;
  readonly spec: AppSpec;
  readonly urlPath: string;
  readonly timeline: readonly BuildStep[];
  readonly usage: AgentUsage;
}

const slugify = (value: string): string => {
  const base = value
    .normalize("NFKD")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 40);
  return base.length === 0 ? "app" : base;
};

const safeSourcePath = (path: string): string => {
  const resolved = resolve("/", path);
  if (relative("/", resolved).startsWith("..")) {
    throw new AppError({
      code: "validation_failed",
      message: `Refusing to write unsafe path "${path}"`,
    });
  }
  return resolved.slice(1);
};

const writeSource = async (directory: string, files: readonly GeneratedFile[]): Promise<void> => {
  for (const file of files) {
    const target = join(directory, safeSourcePath(file.path));
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, file.content, "utf8");
  }
};

/**
 * Prompt → validated spec → deterministic scaffold → published build directory.
 * The model only chooses the app's shape; file contents are generated by the
 * platform, so the output is always consistent and safe to serve.
 */
export const buildApp = async (
  deps: BuilderDeps,
  options: BuildOptions,
): Promise<BuildResult> => {
  const now = deps.now ?? (() => new Date());
  const timeline: BuildStep[] = [];

  const generated = await generateAppSpec({
    prompt: options.prompt,
    model: deps.model,
    modelId: deps.modelId,
    ...(deps.maxOutputTokens === undefined
      ? {}
      : { maxOutputTokens: deps.maxOutputTokens }),
    ...(options.signal === undefined ? {} : { signal: options.signal }),
  });
  timeline.push({
    step: "design",
    status: "ok",
    detail: `${String(generated.spec.entities.length)} collections, ${String(generated.attempts)} model call(s)`,
  });

  const appId = newId();
  const slug = `${slugify(generated.spec.name)}-${appId.slice(0, 8)}`;
  const files = scaffoldApp(generated.spec, { appId, slug });
  timeline.push({
    step: "scaffold",
    status: "ok",
    detail: `${String(files.length)} files`,
  });

  const createdAt = now().toISOString();
  const app = deps.store.createApp({
    id: appId,
    slug,
    prompt: options.prompt,
    spec: generated.spec,
    createdAt,
    inputTokens: generated.usage.inputTokens,
    outputTokens: generated.usage.outputTokens,
    ...(options.ownerId === undefined ? {} : { ownerId: options.ownerId }),
  });

  const sourceDirectory = join(deps.root, "apps", appId, "source");
  try {
    await writeSource(sourceDirectory, files);
    const published = await deps.hosting.publish({
      appId,
      slug,
      files: files.map((file) => ({
        path: file.path,
        content: Buffer.from(file.content, "utf8"),
      })),
    });
    const deployedAt = now().toISOString();
    deps.store.markDeployed(appId, deployedAt);
    timeline.push({ step: "deploy", status: "ok", detail: published.urlPath });
    return {
      app: { ...app, status: "deployed", deployedAt },
      spec: generated.spec,
      urlPath: published.urlPath,
      timeline,
      usage: generated.usage,
    };
  } catch (error) {
    deps.store.markFailed(appId);
    throw error;
  }
};
