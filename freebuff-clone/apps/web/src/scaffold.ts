const escapeHtml = (value: string): string =>
  value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");

const indexHtml = (spec: AppSpec, appId: string): string => `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<meta name="freebuff-app-id" content="${escapeHtml(appId)}" />
<title>${escapeHtml(spec.name)}</title>
<link rel="stylesheet" href="./styles.css" />
</head>
<body>
<header>
  <h1>${escapeHtml(spec.name)}</h1>
  <p class="tagline">${escapeHtml(spec.tagline)}</p>
  <div id="account"></div>
</header>
<main id="app"></main>
<script src="./app.js"></script>
</body>
</html>
`;

