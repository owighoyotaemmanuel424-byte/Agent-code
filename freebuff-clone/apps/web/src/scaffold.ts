/**
 * The generated client is plain ES2020 with no build step: it talks to the
 * platform data API and stores only its own session token. All rendering uses
 * textContent, so stored values cannot inject markup.
 */
const appJs = (spec: AppSpec, appId: string, slug: string): string => {
  const specJson = JSON.stringify(spec).replace(/</g, "\\u003c");
  return `/* Generated by freebuff app builder. Edit freely; this file is yours. */
(function () {
  var SPEC = ${specJson};
  var APP_ID = ${JSON.stringify(appId)};
  var SLUG = ${JSON.stringify(slug)};
  var SESSION_KEY = 'freebuff.session.' + APP_ID;

  function el(tag, attrs, children) {
    var node = document.createElement(tag);
    Object.keys(attrs || {}).forEach(function (key) {
      if (key === 'text') node.textContent = attrs[key];
      else if (key === 'className') node.className = attrs[key];
      else if (key.indexOf('on') === 0) node.addEventListener(key.slice(2), attrs[key]);
      else node.setAttribute(key, attrs[key]);
    });
    (children || []).forEach(function (child) { if (child) node.appendChild(child); });
    return node;
  }

  function token() { return localStorage.getItem(SESSION_KEY); }
  function setToken(value) {
    if (value) localStorage.setItem(SESSION_KEY, value);
    else localStorage.removeItem(SESSION_KEY);
  }

  function api(path, options) {
    var opts = options || {};
    var headers = { 'content-type': 'application/json' };
    if (token()) headers.authorization = 'Bearer ' + token();
    return fetch('/api/apps/' + APP_ID + path, {
      method: opts.method || 'GET',
      headers: headers,
      body: opts.body === undefined ? undefined : JSON.stringify(opts.body)
    }).then(function (response) {
      return response.json().catch(function () { return {}; }).then(function (body) {
        if (!response.ok) {
          var error = new Error(body.message || ('Request failed (' + response.status + ')'));
          error.status = response.status;
          throw error;
        }
        return body;
      });
    });
  }

  function fieldInput(field) {
    var input;
    if (field.type === 'boolean') {
      input = el('input', { type: 'checkbox' });
      input.checked = false;
      return input;
    }
    if (field.type === 'longtext') {
      input = el('textarea', { name: field.name });
    } else {
      input = el('input', { name: field.name, type: field.type === 'integer' ? 'number' : field.type === 'date' ? 'date' : 'text' });
    }
    if (field.required) input.required = true;
    return input;
  }

  function readField(input, field) {
    if (field.type === 'boolean') return input.checked;
    if (field.type === 'integer') {
      if (input.value === '') return field.required ? 0 : null;
      return parseInt(input.value, 10);
    }
    return input.value === '' && !field.required ? null : input.value;
  }

  function renderAccount(account) {
    account.textContent = '';
    if (token()) {
      api('/auth/me').then(function (body) {
        account.appendChild(el('span', { className: 'muted', text: 'Signed in as ' + body.user.email + ' ' }));
        account.appendChild(el('button', {
          className: 'secondary', text: 'Sign out', onclick: function () { setToken(null); render(); }
        }));
      }).catch(function () { setToken(null); renderAccount(account); });
    } else {
      account.appendChild(el('span', { className: 'muted', text: 'Not signed in' }));
    }
  }

  function renderAuth(root) {
    var email = el('input', { type: 'email', placeholder: 'you@example.com', required: 'required' });
    var output = el('div', { className: 'muted' });
    var form = el('form', {
      onsubmit: function (event) {
        event.preventDefault();
        output.textContent = 'Sending link...';
        api('/auth/request', { method: 'POST', body: { email: email.value } }).then(function (body) {
          output.textContent = '';
          output.appendChild(el('div', { text: 'Open your sign-in link: ' }));
          output.appendChild(el('a', { href: body.link, text: body.link }));
        }).catch(function (error) { output.textContent = error.message; });
      }
    }, [
      el('label', { text: 'Email' }, [email]),
      el('button', { type: 'submit', text: 'Email me a link' })
    ]);
    root.appendChild(el('section', {}, [
      el('h2', { text: 'Sign in' }),
      form,
      output
    ]));
  }

  function renderEntity(root, entity) {
    var list = el('ul');
    var message = el('div', { className: 'muted' });
    var inputs = entity.fields.map(function (field) {
      var input = fieldInput(field);
      return { field: field, input: input, label: el('label', { text: field.label + (field.required ? ' *' : '') }, [input]) };
    });
    var form = el('form', {
      onsubmit: function (event) {
        event.preventDefault();
        var body = {};
        inputs.forEach(function (item) { body[item.field.name] = readField(item.input, item.field); });
        message.textContent = 'Saving...';
        api('/data/' + entity.name, { method: 'POST', body: body }).then(function () {
          message.textContent = '';
          inputs.forEach(function (item) {
            if (item.field.type === 'boolean') item.input.checked = false;
            else item.input.value = '';
          });
          load();
        }).catch(function (error) { message.textContent = error.message; message.className = 'error'; });
      }
    }, inputs.map(function (item) { return item.label; }).concat([el('button', { type: 'submit', text: 'Add' })]));

    function load() {
      list.textContent = '';
      if (!token()) {
        list.appendChild(el('li', {}, [el('span', { className: 'muted', text: 'Sign in to see your ' + entity.label.toLowerCase() + '.' })]));
        return;
      }
      api('/data/' + entity.name).then(function (body) {
        if (body.rows.length === 0) {
          list.appendChild(el('li', {}, [el('span', { className: 'muted', text: 'Nothing here yet.' })]));
        }
        body.rows.forEach(function (row) {
          var summary = entity.fields.map(function (field) {
            var value = row[field.name];
            if (value === null || value === undefined) return '';
            return field.label + ': ' + String(value);
          }).filter(Boolean).join('  |  ');
          list.appendChild(el('li', {}, [
            el('span', { text: summary }),
            el('button', {
              className: 'secondary', text: 'Delete',
              onclick: function () {
                api('/data/' + entity.name + '/' + row.id, { method: 'DELETE' }).then(load).catch(function (error) {
                  message.textContent = error.message;
                  message.className = 'error';
                });
              }
            })
          ]));
        });
      }).catch(function (error) { message.textContent = error.message; message.className = 'error'; });
    }

    root.appendChild(el('section', {}, [
      el('h2', { text: entity.label }),
      form,
      message,
      list
    ]));
    load();
    return load;
  }

  function renderFiles(root) {
    var input = el('input', { type: 'file' });
    var message = el('div', { className: 'muted' });
    var list = el('ul');
    function load() {
      list.textContent = '';
      if (!token()) return;
      api('/files').then(function (body) {
        if (body.files.length === 0) {
          list.appendChild(el('li', {}, [el('span', { className: 'muted', text: 'No files uploaded.' })]));
        }
        body.files.forEach(function (file) {
          list.appendChild(el('li', {}, [
            el('span', { text: file.name + ' (' + Math.ceil(file.size / 1024) + ' KB)' }),
            el('a', { href: '/api/apps/' + APP_ID + '/files/' + file.id, text: 'Download' })
          ]));
        });
      }).catch(function () {});
    }
    var form = el('form', {
      onsubmit: function (event) {
        event.preventDefault();
        var file = input.files[0];
        if (!file) return;
        var reader = new FileReader();
        reader.onload = function () {
          var base64 = String(reader.result).split(',')[1] || '';
          message.textContent = 'Uploading...';
          api('/files', {
            method: 'POST',
            body: { name: file.name, contentType: file.type || 'application/octet-stream', contentBase64: base64 }
          }).then(function () {
            message.textContent = '';
            input.value = '';
            load();
          }).catch(function (error) { message.textContent = error.message; message.className = 'error'; });
        };
        reader.readAsDataURL(file);
      }
    }, [el('label', { text: 'Upload a file (max 2 MB)' }, [input]), el('button', { type: 'submit', text: 'Upload' })]);
    root.appendChild(el('section', {}, [el('h2', { text: 'Files' }), form, message, list]));
    load();
  }

  function render() {
    var account = document.getElementById('account');
    var root = document.getElementById('app');
    root.textContent = '';
    renderAccount(account);
    if (!token()) {
      renderAuth(root);
      return;
    }
    SPEC.entities.forEach(function (entity) { renderEntity(root, entity); });
    renderFiles(root);
  }

  render();
})();
`;
};

const readme = (spec: AppSpec): string => `# ${spec.name}

${spec.tagline}

Generated by the freebuff app builder from one prompt.

## Layout

- \`index.html\`, \`styles.css\`, \`app.js\` — the client. No build step.
- \`schema.sql\` — the tables the app uses.
- \`freebuff.app.json\` — the validated app specification.

## Running it

The client talks to the freebuff data API for auth, records and files. It is
served at its deployed URL; \`app.js\` derives the app id from the page's
\`meta[name=freebuff-app-id]\` tag.

## Data model

${spec.entities
  .map(
    (entity) =>
      `- **${entity.label}** (\`${entity.name}\`): ${entity.fields
        .map((field) => `${field.name} ${field.type}${field.required ? " required" : ""}`)
        .join(", ")}`,
  )
  .join("\n")}

Every row is owned by the signed-in user; the API filters by owner in SQL.
`;

export const scaffoldApp = (
  spec: AppSpec,
  options: { readonly appId: string; readonly slug: string },
): GeneratedFile[] => [
  { path: "index.html", content: indexHtml(spec, options.appId) },
  { path: "styles.css", content: stylesCss(spec) },
  { path: "app.js", content: appJs(spec, options.appId, options.slug) },
  { path: "schema.sql", content: schemaToSql(appSpecToSchema(spec)) },
  { path: "README.md", content: readme(spec) },
];
